void shellSort(int data[], int n) {
    // 1. กำหนดระยะห่าง (Gap หรือ D) เริ่มต้นที่ n/2 
    // และลดลงทีละครึ่งในแต่ละรอบจนกระทั่ง D = 1 
    for (int D = n / 2; D > 0; D /= 2) {
        
        // 2. ทำการจัดเรียงแบบ Insertion Sort 
        // สำหรับกลุ่มข้อมูลที่ห่างกันเท่ากับ D 
        for (int i = D; i < n; i++) {
            // จองค่าที่กำลังจะตรวจสอบ 
            int tmp = data[i]; 
            int j = i;

            /* 3. เปรียบเทียบและขยับข้อมูลที่ห่างกันเป็นระยะ D 
               ถ้าตัวก่อนหน้า (D ช่อง) มีค่ามากกว่าตัวปัจจุบัน 
               ให้ขยับตัวนั้นมาทางขวา */
            while (j >= D && data[j - D] > tmp) {
                data[j] = data[j - D]; // ขยับข้อมูล
                // ถอยกลับไปเช็คตัวถัดไปที่ห่างกัน D ช่อง  
                j -= D;                
            }

            // 4. วางค่าที่เก็บไว้ลงในตำแหน่งที่ถูกต้อง
            data[j] = tmp; 
        }
    }
}