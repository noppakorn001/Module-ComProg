void insertionSort(int data[], int n) {
    // เริ่มจากตัวที่ 2 เพราะเราถือว่า index 0 เรียงเสร็จแล้ว
    for (int i = 1; i < n; i++) {
        
        int tmp = data[i]; // tmp = ค่าที่เรากำลังจะหยิบไปหาที่วาง
        int j = i - 1;     // j = ตำแหน่งสุดท้ายของกลุ่มที่เรียงแล้ว

        /* วนลูปถอยหลังเพื่อเปรียบเทียบ 'tmp' กับกลุ่มที่เรียงแล้วทางซ้าย
           ถ้าตัวซ้ายมือ (data[j]) ยังมีค่ามากกว่า 'tmp'
           ให้ "ขยับ" ตัวนั้นไปทางขวา 1 ช่อง เพื่อเปิดพื้นที่ว่าง 
        */
        while (j >= 0 && data[j] > tmp) {
            data[j + 1] = data[j]; // ขยับข้อมูลไปทางขวา 
            j = j - 1;             // ถอยไปดูตัวถัดไปทางซ้าย
        }

        // เมื่อเจอที่ว่างที่เหมาะสม (หรือถึงขอบซ้ายสุด) ให้วาง 'tmp' ลงไป 
        data[j + 1] = tmp; 
    }
}